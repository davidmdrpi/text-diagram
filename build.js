#!/usr/bin/env node
/*
 * Builds text-diagram.html: a single self-contained file (no CDN, no directory
 * structure) that people can download and open directly, even offline.
 *
 *   npm install && npm run build
 *
 * It inlines src/engine.js and src/app.js, and replaces the Tailwind CDN script
 * with CSS compiled for exactly the classes the app uses.
 */
'use strict';
const fs = require('node:fs');
const path = require('node:path');
const { execFileSync } = require('node:child_process');

const root = __dirname;
const read = (p) => fs.readFileSync(path.join(root, p), 'utf8');

function compileCss() {
  const bin = path.join(root, 'node_modules', '.bin', process.platform === 'win32' ? 'tailwindcss.cmd' : 'tailwindcss');
  if (!fs.existsSync(bin)) {
    console.error('tailwindcss not installed: run `npm install` first.');
    process.exit(1);
  }
  return execFileSync(bin, ['-c', 'tailwind.config.js', '-i', 'src/tailwind.css', '--minify'], {
    cwd: root,
    encoding: 'utf8',
    stdio: ['ignore', 'pipe', 'ignore'],
  }).trim();
}

function inlineScript(file) {
  const js = read(file);
  if (/<\/script/i.test(js)) throw new Error(`${file} contains "</script" and cannot be inlined`);
  return `<script>\n/* ---- ${file} ---- */\n${js}</script>`;
}

let html = read('index.html');
const replaceOnce = (pattern, replacement, label) => {
  const before = html;
  html = html.replace(pattern, () => replacement);
  if (html === before) throw new Error(`build: could not find ${label} in index.html`);
};

replaceOnce(/[ \t]*<script src="https:\/\/cdn\.tailwindcss\.com[^"]*"><\/script>\n/, '', 'Tailwind CDN script');
replaceOnce(/[ \t]*<script>\s*if \(window\.tailwind\)[\s\S]*?<\/script>\n/, `  <style>${compileCss()}</style>\n`, 'inline tailwind.config');
replaceOnce('<script src="src/engine.js"></script>', inlineScript('src/engine.js'), 'engine.js script tag');
replaceOnce('<script src="src/app.js"></script>', inlineScript('src/app.js'), 'app.js script tag');
html = html.replace('<!DOCTYPE html>', '<!DOCTYPE html>\n<!-- text-diagram: single-file build. Generated by build.js from index.html + src/ — edit those, then run `npm run build`. -->');

fs.writeFileSync(path.join(root, 'text-diagram.html'), html);
console.log(`wrote text-diagram.html (${(Buffer.byteLength(html) / 1024).toFixed(1)} KB)`);
